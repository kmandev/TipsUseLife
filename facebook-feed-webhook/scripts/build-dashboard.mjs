// Bundles dashboard/{index.html,app.js,app.css} into src/dashboard.js so the
// Worker (and the Node test runner) can import them as plain strings.
// Run: npm run build:dashboard   (tests fail if the output is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => readFileSync(join(root, "dashboard", f), "utf8");

export function renderDashboardModule() {
  return `// GENERATED by scripts/build-dashboard.mjs from dashboard/*. Do not edit.
export const DASHBOARD_HTML = ${JSON.stringify(read("index.html"))};
export const DASHBOARD_JS = ${JSON.stringify(read("app.js"))};
export const DASHBOARD_CSS = ${JSON.stringify(read("app.css"))};
export const DASHBOARD_CSP = ${JSON.stringify(
    [
      "default-src 'none'",
      "script-src 'self'",
      "style-src 'self' https://fonts.googleapis.com",
      "font-src https://fonts.gstatic.com",
      "img-src 'self' https: data:",
      "connect-src 'self'",
      "base-uri 'none'",
      "form-action 'self'",
      "frame-ancestors 'none'",
    ].join("; ")
  )};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "src", "dashboard.js"), renderDashboardModule());
  console.log("src/dashboard.js written");
}
